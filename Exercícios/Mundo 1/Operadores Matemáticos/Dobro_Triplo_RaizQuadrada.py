'Algoritmo que leia um número e mostre o seu dobro, triplo e a sua raiz quadrada'

n = int(input("Digite um número: "))
dobro = n * 2
triplo = n * 3
raiz = n**(1/2)
print(' O seu número é: {}'.format(n))
print(' Dobro dele é: ', dobro)
print(' Triplo dele é: ', triplo)
print(' Raiz dele é: ', round(raiz, 3))

